-- Multi-player AI Incident Room demo: put the pipeline back exactly as setup.sql left it, and clear room state.
--   snow sql --connection <name> -f demo/reset.sql

USE ROLE ACCOUNTADMIN;
USE WAREHOUSE INCIDENT_ROOM_WH;

-- Undo the upstream rename if it is in place.
EXECUTE IMMEDIATE $$
BEGIN
  IF (EXISTS (SELECT 1 FROM INCIDENT_ROOM_DEMO.INFORMATION_SCHEMA.COLUMNS
              WHERE TABLE_SCHEMA = 'SALES' AND TABLE_NAME = 'RAW_ORDERS' AND COLUMN_NAME = 'ORDER_AMOUNT')) THEN
    ALTER TABLE INCIDENT_ROOM_DEMO.SALES.RAW_ORDERS RENAME COLUMN ORDER_AMOUNT TO AMOUNT;
  END IF;
  RETURN 'ok';
END;
$$;

-- Restore the original task body. ACCOUNTADMIN inherits INCIDENT_ROOM_SHIPPER, the task's owner.
ALTER TASK INCIDENT_ROOM_DEMO.SALES.LOAD_DAILY_REVENUE MODIFY AS
  INSERT OVERWRITE INTO INCIDENT_ROOM_DEMO.SALES.DAILY_REVENUE
  SELECT ORDER_DATE, REGION, SUM(AMOUNT), COUNT(*) FROM INCIDENT_ROOM_DEMO.SALES.RAW_ORDERS GROUP BY ORDER_DATE, REGION;

-- Drop every incident clone.
EXECUTE IMMEDIATE $$
DECLARE
  c CURSOR FOR SELECT SCHEMA_NAME FROM INCIDENT_ROOM_CLONES.INFORMATION_SCHEMA.SCHEMATA
               WHERE SCHEMA_NAME NOT IN ('INFORMATION_SCHEMA', 'PUBLIC');
BEGIN
  FOR r IN c DO
    EXECUTE IMMEDIATE 'DROP SCHEMA IF EXISTS INCIDENT_ROOM_CLONES.' || r.SCHEMA_NAME;
  END FOR;
  RETURN 'ok';
END;
$$;

-- Clear room state (keeps postmortems so past demos remain readable).
DELETE FROM INCIDENT_ROOM.APP.VOTES;
DELETE FROM INCIDENT_ROOM.APP.PATCHES;
DELETE FROM INCIDENT_ROOM.APP.EVENTS;
DELETE FROM INCIDENT_ROOM.APP.INCIDENTS;

-- Run the load once so the latest run is healthy again.
EXECUTE TASK INCIDENT_ROOM_DEMO.SALES.LOAD_DAILY_REVENUE;
