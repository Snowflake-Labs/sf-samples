-- =============================================================================
-- Multi-player AI Incident Room — Snowflake setup (idempotent)
-- =============================================================================
--   snow sql --connection <name> -f setup.sql
-- Run as ACCOUNTADMIN (creates roles, a warehouse, three databases, three agents).
--
-- Trust model (who can do what):
--   INCIDENT_ROOM_AGENT    the role the app pins when it calls an agent. It can only
--                     run the agents and their tools.
--   INCIDENT_ROOM_OPS      owns the agent tools (owner's rights). Reads the demo
--                     pipeline; creates objects ONLY in INCIDENT_ROOM_CLONES; writes
--                     patches and postmortems.
--   INCIDENT_ROOM_SHIPPER  owns the production task and SHIP_FIX. SHIP_FIX re-checks
--                     the votes in INCIDENT_ROOM.APP.VOTES itself before it touches prod.
-- No agent role can call SHIP_FIX.
-- =============================================================================

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS INCIDENT_ROOM_AGENT   COMMENT = 'Multi-player AI Incident Room: runs the three agents and their tools';
CREATE ROLE IF NOT EXISTS INCIDENT_ROOM_OPS     COMMENT = 'Multi-player AI Incident Room: owns agent tools; writes only to INCIDENT_ROOM_CLONES and room tables';
CREATE ROLE IF NOT EXISTS INCIDENT_ROOM_SHIPPER COMMENT = 'Multi-player AI Incident Room: owns the prod task and SHIP_FIX';
GRANT ROLE INCIDENT_ROOM_AGENT   TO ROLE ACCOUNTADMIN;
GRANT ROLE INCIDENT_ROOM_OPS     TO ROLE ACCOUNTADMIN;
GRANT ROLE INCIDENT_ROOM_SHIPPER TO ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS INCIDENT_ROOM_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Multi-player AI Incident Room: agents, tools and the demo pipeline';
GRANT USAGE ON WAREHOUSE INCIDENT_ROOM_WH TO ROLE INCIDENT_ROOM_AGENT;
GRANT USAGE ON WAREHOUSE INCIDENT_ROOM_WH TO ROLE INCIDENT_ROOM_OPS;
GRANT USAGE ON WAREHOUSE INCIDENT_ROOM_WH TO ROLE INCIDENT_ROOM_SHIPPER;
USE WAREHOUSE INCIDENT_ROOM_WH;

-- The agents call Cortex; don't rely on CORTEX_USER being granted to PUBLIC.
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE INCIDENT_ROOM_AGENT;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE INCIDENT_ROOM_SHIPPER;

-- -----------------------------------------------------------------------------
-- 1. The demo pipeline (the "factory" that will break)
--    RAW_ORDERS --(task LOAD_DAILY_REVENUE)--> DAILY_REVENUE --> REVENUE_BY_REGION_V --> EXEC_SCORECARD_V
-- -----------------------------------------------------------------------------
CREATE DATABASE IF NOT EXISTS INCIDENT_ROOM_DEMO COMMENT = 'Multi-player AI Incident Room demo pipeline';
CREATE SCHEMA IF NOT EXISTS INCIDENT_ROOM_DEMO.SALES;

CREATE TABLE IF NOT EXISTS INCIDENT_ROOM_DEMO.SALES.RAW_ORDERS (
  ORDER_ID NUMBER, ORDER_DATE DATE, REGION VARCHAR, AMOUNT NUMBER(12,2)
) COMMENT = 'Raw orders landed by the upstream team';
INSERT INTO INCIDENT_ROOM_DEMO.SALES.RAW_ORDERS
SELECT SEQ4() + 1,
       DATEADD(day, MOD(SEQ4(), 30), '2026-10-01'::DATE),
       ARRAY_CONSTRUCT('AMER', 'EMEA', 'APJ', 'LATAM')[MOD(SEQ4(), 4)]::VARCHAR,
       MOD(SEQ4() * 37, 500) + 10
FROM TABLE(GENERATOR(ROWCOUNT => 2000))
WHERE NOT EXISTS (SELECT 1 FROM INCIDENT_ROOM_DEMO.SALES.RAW_ORDERS);

CREATE TABLE IF NOT EXISTS INCIDENT_ROOM_DEMO.SALES.DAILY_REVENUE (
  DAY DATE, REGION VARCHAR, REVENUE NUMBER(14,2), ORDERS NUMBER
) COMMENT = 'Daily revenue by region, rebuilt by LOAD_DAILY_REVENUE';

CREATE OR REPLACE VIEW INCIDENT_ROOM_DEMO.SALES.REVENUE_BY_REGION_V
  COMMENT = 'Revenue by region for the RevOps dashboard'
AS SELECT REGION, SUM(REVENUE) AS REVENUE, SUM(ORDERS) AS ORDERS
   FROM INCIDENT_ROOM_DEMO.SALES.DAILY_REVENUE GROUP BY REGION;

CREATE OR REPLACE VIEW INCIDENT_ROOM_DEMO.SALES.EXEC_SCORECARD_V
  COMMENT = 'Exec scorecard tile: total revenue'
AS SELECT SUM(REVENUE) AS TOTAL_REVENUE, SUM(ORDERS) AS TOTAL_ORDERS
   FROM INCIDENT_ROOM_DEMO.SALES.REVENUE_BY_REGION_V;

-- The task stays SUSPENDED (the demo runs it with EXECUTE TASK) so it never costs credits on a schedule.
CREATE TASK IF NOT EXISTS INCIDENT_ROOM_DEMO.SALES.LOAD_DAILY_REVENUE
  WAREHOUSE = INCIDENT_ROOM_WH
  SCHEDULE = 'USING CRON 0 6 * * * UTC'
  COMMENT = 'Rebuilds DAILY_REVENUE from RAW_ORDERS'
AS
  INSERT OVERWRITE INTO INCIDENT_ROOM_DEMO.SALES.DAILY_REVENUE
  SELECT ORDER_DATE, REGION, SUM(AMOUNT), COUNT(*) FROM INCIDENT_ROOM_DEMO.SALES.RAW_ORDERS GROUP BY ORDER_DATE, REGION;

-- On a re-run after demo/break.sql, undo the upstream rename so the first load below works.
EXECUTE IMMEDIATE $$
BEGIN
  IF (EXISTS (SELECT 1 FROM INCIDENT_ROOM_DEMO.INFORMATION_SCHEMA.COLUMNS
              WHERE TABLE_SCHEMA = 'SALES' AND TABLE_NAME = 'RAW_ORDERS' AND COLUMN_NAME = 'ORDER_AMOUNT')) THEN
    ALTER TABLE INCIDENT_ROOM_DEMO.SALES.RAW_ORDERS RENAME COLUMN ORDER_AMOUNT TO AMOUNT;
  END IF;
  RETURN 'ok';
END;
$$;

-- First good load, so prod has a "last known good" to compare a fix against.
INSERT OVERWRITE INTO INCIDENT_ROOM_DEMO.SALES.DAILY_REVENUE
SELECT ORDER_DATE, REGION, SUM(AMOUNT), COUNT(*) FROM INCIDENT_ROOM_DEMO.SALES.RAW_ORDERS GROUP BY ORDER_DATE, REGION;

GRANT OWNERSHIP ON TASK INCIDENT_ROOM_DEMO.SALES.LOAD_DAILY_REVENUE TO ROLE INCIDENT_ROOM_SHIPPER COPY CURRENT GRANTS;
GRANT USAGE ON DATABASE INCIDENT_ROOM_DEMO TO ROLE INCIDENT_ROOM_SHIPPER;
GRANT USAGE ON SCHEMA INCIDENT_ROOM_DEMO.SALES TO ROLE INCIDENT_ROOM_SHIPPER;
GRANT SELECT ON TABLE INCIDENT_ROOM_DEMO.SALES.RAW_ORDERS TO ROLE INCIDENT_ROOM_SHIPPER;
GRANT SELECT, INSERT, DELETE, TRUNCATE ON TABLE INCIDENT_ROOM_DEMO.SALES.DAILY_REVENUE TO ROLE INCIDENT_ROOM_SHIPPER;

-- OPS reads everything in the demo schema (to triage and to clone) and can see the task's history.
GRANT USAGE ON DATABASE INCIDENT_ROOM_DEMO TO ROLE INCIDENT_ROOM_OPS;
GRANT USAGE ON SCHEMA INCIDENT_ROOM_DEMO.SALES TO ROLE INCIDENT_ROOM_OPS;
GRANT SELECT ON ALL TABLES IN SCHEMA INCIDENT_ROOM_DEMO.SALES TO ROLE INCIDENT_ROOM_OPS;
GRANT SELECT ON ALL VIEWS IN SCHEMA INCIDENT_ROOM_DEMO.SALES TO ROLE INCIDENT_ROOM_OPS;
GRANT MONITOR ON TASK INCIDENT_ROOM_DEMO.SALES.LOAD_DAILY_REVENUE TO ROLE INCIDENT_ROOM_OPS;
GRANT VIEW LINEAGE ON ACCOUNT TO ROLE INCIDENT_ROOM_OPS;

-- -----------------------------------------------------------------------------
-- 2. The clone sandbox: the only place an agent can create or change anything
-- -----------------------------------------------------------------------------
CREATE DATABASE IF NOT EXISTS INCIDENT_ROOM_CLONES COMMENT = 'Multi-player AI Incident Room: zero-copy clones where agents test fixes. Dropped when an incident closes.';
GRANT USAGE, CREATE SCHEMA ON DATABASE INCIDENT_ROOM_CLONES TO ROLE INCIDENT_ROOM_OPS;

-- -----------------------------------------------------------------------------
-- 3. Room state
-- -----------------------------------------------------------------------------
CREATE DATABASE IF NOT EXISTS INCIDENT_ROOM COMMENT = 'Multi-player AI Incident Room app';
CREATE SCHEMA IF NOT EXISTS INCIDENT_ROOM.APP    COMMENT = 'Room state written by the app';
CREATE SCHEMA IF NOT EXISTS INCIDENT_ROOM.AGENTS COMMENT = 'Agents and their tools';

CREATE TABLE IF NOT EXISTS INCIDENT_ROOM.APP.INCIDENTS (
  ID VARCHAR NOT NULL, TITLE VARCHAR, OBJECT_FQN VARCHAR, ERROR_MESSAGE VARCHAR,
  STATUS VARCHAR NOT NULL,            -- TRIAGE | FIXING | VOTING | SHIPPED | CLOSED
  FROZEN BOOLEAN DEFAULT FALSE, FROZEN_BY VARCHAR, FROZEN_REASON VARCHAR,
  REQUIRED_APPROVALS NUMBER DEFAULT 2,
  OPENED_BY VARCHAR, OPENED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(), CLOSED_AT TIMESTAMP_LTZ,
  THREADS VARIANT                     -- {"TRIAGE": <thread id>, ...}
);
CREATE TABLE IF NOT EXISTS INCIDENT_ROOM.APP.EVENTS (
  ID VARCHAR, INCIDENT_ID VARCHAR, AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
  BY_WHO VARCHAR, KIND VARCHAR, PAYLOAD VARIANT
);
CREATE TABLE IF NOT EXISTS INCIDENT_ROOM.APP.PATCHES (
  ID VARCHAR, INCIDENT_ID VARCHAR, TASK_FQN VARCHAR, TASK_SQL VARCHAR,
  CLONE_SCHEMA VARCHAR, TESTED_OK BOOLEAN, TEST_RESULT VARIANT,
  PROPOSED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(), SHIPPED_AT TIMESTAMP_LTZ, SHIPPED_BY VARCHAR
);
CREATE TABLE IF NOT EXISTS INCIDENT_ROOM.APP.VOTES (
  PATCH_ID VARCHAR, VOTER VARCHAR, VOTE VARCHAR, AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE TABLE IF NOT EXISTS INCIDENT_ROOM.APP.POSTMORTEMS (
  INCIDENT_ID VARCHAR, BODY VARCHAR, WRITTEN_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);
-- Decisions filed with /file: append-only, attributed, with who was in the room.
CREATE TABLE IF NOT EXISTS INCIDENT_ROOM.APP.DECISIONS (
  ID VARCHAR, INCIDENT_ID VARCHAR, FILED_BY VARCHAR, PARTICIPANTS ARRAY, BODY VARCHAR,
  FILED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

GRANT USAGE ON DATABASE INCIDENT_ROOM TO ROLE INCIDENT_ROOM_AGENT;
GRANT USAGE ON SCHEMA INCIDENT_ROOM.AGENTS TO ROLE INCIDENT_ROOM_AGENT;
GRANT USAGE ON DATABASE INCIDENT_ROOM TO ROLE INCIDENT_ROOM_OPS;
GRANT USAGE ON SCHEMA INCIDENT_ROOM.APP TO ROLE INCIDENT_ROOM_OPS;
GRANT USAGE, CREATE PROCEDURE ON SCHEMA INCIDENT_ROOM.AGENTS TO ROLE INCIDENT_ROOM_OPS;
GRANT SELECT ON TABLE INCIDENT_ROOM.APP.INCIDENTS TO ROLE INCIDENT_ROOM_OPS;
GRANT SELECT ON TABLE INCIDENT_ROOM.APP.EVENTS TO ROLE INCIDENT_ROOM_OPS;
GRANT SELECT, INSERT ON TABLE INCIDENT_ROOM.APP.PATCHES TO ROLE INCIDENT_ROOM_OPS;
GRANT SELECT, INSERT ON TABLE INCIDENT_ROOM.APP.POSTMORTEMS TO ROLE INCIDENT_ROOM_OPS;
GRANT SELECT ON TABLE INCIDENT_ROOM.APP.DECISIONS TO ROLE INCIDENT_ROOM_OPS;
GRANT USAGE ON DATABASE INCIDENT_ROOM TO ROLE INCIDENT_ROOM_SHIPPER;
GRANT USAGE ON SCHEMA INCIDENT_ROOM.APP TO ROLE INCIDENT_ROOM_SHIPPER;
GRANT USAGE, CREATE PROCEDURE ON SCHEMA INCIDENT_ROOM.AGENTS TO ROLE INCIDENT_ROOM_SHIPPER;
GRANT SELECT ON TABLE INCIDENT_ROOM.APP.INCIDENTS TO ROLE INCIDENT_ROOM_SHIPPER;
GRANT SELECT ON TABLE INCIDENT_ROOM.APP.VOTES TO ROLE INCIDENT_ROOM_SHIPPER;
GRANT SELECT, UPDATE ON TABLE INCIDENT_ROOM.APP.PATCHES TO ROLE INCIDENT_ROOM_SHIPPER;

