#!/usr/bin/env python3
"""Generate dcm/sources/macros/verified_queries.sql from examples/prompts.json.

DCM Jinja cannot read JSON, so the semantic view's verified queries are compiled
into a macro. Run after editing prompts.json; tests fail if the macro is stale.
"""

from __future__ import annotations

import json
from pathlib import Path
from string import Template

import install

ROOT = Path(__file__).resolve().parents[1]
MACRO = ROOT / "dcm/sources/macros/verified_queries.sql"
NS = "@@NS@@"


def condition(prompt: dict) -> str | None:
    optional = sorted(set(prompt["requires"]) - set(install.THEMES))
    if not optional:
        return None
    return " and ".join(f"'{theme}' in optional_themes" for theme in optional)


def render() -> str:
    """Macro whose output equals install.verified_queries() for any theme set.

    Tags sit inline with no whitespace control, so the result does not depend on
    the trim settings of the Jinja environment that renders it.
    """
    prompts = json.loads((ROOT / "examples/prompts.json").read_text())
    if not prompts or condition(prompts[0]) is not None:
        raise ValueError("The first prompt must need only core themes, so the list is never empty")
    body = "ai_verified_queries (\n"
    for index, prompt in enumerate(prompts):
        sql = Template(prompt["reference_sql"]).substitute(ns=NS)
        item = (f"{prompt['id']} as (question {install.literal(prompt['question'])} "
                f"sql {install.literal(sql)})")
        if any(tag in item for tag in ("{{", "{%", "{#")):
            raise ValueError(f"Prompt {prompt['id']} contains Jinja syntax")
        item = (",\n" if index else "") + item.replace(NS, "{{ ns }}")
        when = condition(prompt)
        body += f"{{% if {when} %}}{item}{{% endif %}}" if when else item
    return ("{#- Generated by scripts/build_dcm.py from examples/prompts.json. Do not edit. -#}\n"
            "{% macro verified_queries(ns, optional_themes) %}" + body + "\n){% endmacro %}\n")


def main() -> None:
    MACRO.write_text(render())
    print(f"Wrote {MACRO.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
